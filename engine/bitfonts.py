def width(font, s, scale=1):
    if not s:
        return 0
    return sum((len(font.get(ch, font[" "])[0]) + 1) * scale for ch in s) - scale


def draw(canvas, font, s, x, y, rgb, scale=1, clip=(0, 63)):
    """Draw s with its TOP-left corner at (x, y). Returns how far it advanced.
    Pixels outside the clip columns are skipped (used for scrolling text)."""
    r, g, b = rgb
    cx = x
    for ch in s:
        glyph = font.get(ch, font[" "])
        for row, bits in enumerate(glyph):
            for col, bit in enumerate(bits):
                if bit == "1":
                    for a in range(scale):
                        for c in range(scale):
                            px, py = cx + col * scale + a, y + row * scale + c
                            if clip[0] <= px <= clip[1] and 0 <= py < 32:
                                canvas.SetPixel(px, py, r, g, b)
        cx += (len(glyph[0]) + 1) * scale
    return cx - x
